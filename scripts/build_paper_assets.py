def _run_cost(
    record: RunDirRecord, episode_costs: list[float | None], harnessed: bool
) -> tuple[float, bool]:
    """(list cost of one stored run directory, whether it was priced).

    A retained-harness run's own recorded total is authoritative: it prices
    every request on its day and also bills the partial episodes of seeds
    that failed. Otherwise the run is its episodes priced on their day, and
    a run with no priceable episodes falls back to its recorded cost (the
    static-probe arm, a failed_run.json)."""
    recorded = (record.summary or record.failed_run or {}).get("cost_usd_list_price")
    if harnessed and recorded is not None:
        # The recorded total is rounded to 4 dp; never let rounding put it
        # below the exact sum of the episodes it contains.
        exact = sum(episode_costs) if all(c is not None for c in episode_costs) else 0.0
        return max(float(recorded), exact), True
    if episode_costs and all(c is not None for c in episode_costs):
        return float(sum(episode_costs)), True
    if recorded is not None:
        return float(recorded), True
    return 0.0, not episode_costs and record.failed_run is None and record.summary is not None


def tree_spend(tree: Path) -> dict[str, object]:
    """Price EVERY stored run directory under `tree` at list prices.

    Per-episode from result.usage where episodes exist (which reproduces the
    recorded run-level cost unless a published rate was corrected after
    collection), falling back to the run's own recorded
    cost for episode-less runs such as the static-probe arm. Directories with
    no summary.json are priced like any other: that omission was the whole of
    the "total collection cost" defect.
    """
    total = 0.0
    episodes = 0
    api_calls = 0
    run_dirs = 0
    no_summary_dirs = 0
    no_summary_episodes = 0
    no_summary_cost = 0.0
    failed_seed_cost = 0.0
    unpriced: list[str] = []

    for record in scan_run_dirs(tree):
        run_dirs += 1
        on = run_date(record.name)
        episode_costs: list[float | None] = []
        harnessed = False
        for ep_path in record.seed_paths:
            doc = json.loads(ep_path.read_text(encoding="utf-8"))
            result = doc["result"]
            harnessed = harnessed or harness_cost(doc) is not None
            episode_costs.append(episode_list_cost(record.model, doc, on))
            api_calls += result.get("api_calls") or 0
            episodes += 1
        cost, priced = _run_cost(record, episode_costs, harnessed)
        if not priced:
            unpriced.append(f"{record.tree}/{record.name}")
        if record.has_summary and all(c is not None for c in episode_costs):
            # Billed partial episodes of seeds that failed inside a summarized
            # run: in the run's recorded total, in no episode file.
            failed_seed_cost += max(0.0, cost - sum(episode_costs))
        total += cost
        if not record.has_summary:
            no_summary_dirs += 1
            no_summary_episodes += len(record.seed_paths)
            no_summary_cost += cost

    return {
        "tree": _tree_label(tree),
        "cost_usd": total,
        "episodes": episodes,
        "api_calls": api_calls,
        "run_dirs": run_dirs,
        "no_summary_dirs": no_summary_dirs,
        "no_summary_episodes": no_summary_episodes,
        "no_summary_cost_usd": no_summary_cost,
        "failed_seed_cost_usd": failed_seed_cost,
        "unpriced": unpriced,
    }


def campaign_spend(repo_root: Path = REPO_ROOT) -> dict[str, object]:
    """List-price spend per results tree plus the all-arms total."""
    arms = {name: tree_spend(repo_root / path) for name, path in CAMPAIGN_TREES}
    return {
        "arms": arms,
        "total_cost_usd": sum(arm["cost_usd"] for arm in arms.values()),
        "total_episodes": sum(arm["episodes"] for arm in arms.values()),
        "total_api_calls": sum(arm["api_calls"] for arm in arms.values()),
    }


def ladder_cost(cells: dict[tuple[str, str, str], dict]) -> dict[str, object]:
    """Price of replicating the default-effort gauntlet ladder once.

    One canonical attempt per cell -- i.e. exactly the episodes the ladder's
    printed accuracies come from -- so the quoted replication price and the
    quoted scores describe the same runs.
    """
    board_default = {model: easy for model, easy, _top in BOARD_ROSTER}
    rows = [
        cell
        for cell in cells.values()
        if cell["tier"] == LADDER_TIER
        and (
            cell["effort"] == board_default[cell["model"]]
            if cell["model"] in board_default
            else cell["effort"] in LADDER_DEFAULT_EFFORTS
        )
    ]
    rows.sort(key=lambda cell: cell["cost_usd"])
    return {
        "models": len(rows),
        "episodes": sum(cell["n"] for cell in rows),
        "cost_usd": sum(cell["cost_usd"] for cell in rows),
        "all_attempt_cost_usd": sum(cell["all_attempt_cost_usd"] for cell in rows),
        "cheapest": (rows[0]["model"], rows[0]["cost_usd"]) if rows else None,
        "dearest": (rows[-1]["model"], rows[-1]["cost_usd"]) if rows else None,
    }


def _grouped(value: int) -> str:
    """1234567 -> '1{,}234{,}567' (LaTeX-safe thousands separator)."""
    return f"{value:,}".replace(",", "{,}")


def _usd(value: float) -> str:
    """Bare 2-dp number for a \\newcommand body; the paper supplies the $."""
    return f"{value:.2f}"


