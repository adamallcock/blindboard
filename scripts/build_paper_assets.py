def snapshot_stats(results_dir: Path) -> dict[str, object]:
    """Totals over run dirs that carry a summary.json.

    NOTE (M5): this is the SUMMARIZED SUBSET, not the campaign. It is what the
    legacy \\snapshotcostlist macro reports and it is knowingly blind to
    completed no-summary partials. Use campaign_spend() for any "total
    collection cost" claim.
    """
    total_episodes = 0
    total_cost = 0.0
    total_calls = 0
    calls_missing_any = False
    models: set[str] = set()
    tiers: set[str] = set()

    for record in scan_run_dirs(results_dir):
        if not record.has_summary:
            continue
        summary = record.summary
        total_episodes += summary.get("episodes") or 0
        models.add(summary["model"])
        tiers.add(summary["tier"])
        on = run_date(record.name)
        episode_costs: list[float | None] = []
        harnessed = False
        for ep_path in record.seed_paths:
            doc = json.loads(ep_path.read_text(encoding="utf-8"))
            result = doc["result"]
            harnessed = harnessed or harness_cost(doc) is not None
            episode_costs.append(episode_list_cost(record.model, doc, on))
            # Per spec: sum result.api_calls where present; skip the
            # episodes*horizon fallback estimate entirely and just flag
            # whether any episode was missing the field.
            api_calls = result.get("api_calls")
            if api_calls is not None:
                total_calls += api_calls
            else:
                calls_missing_any = True
        total_cost += _run_cost(record, episode_costs, harnessed)[0]

    return {
        "episodes": total_episodes,
        "cost_list": round(total_cost),
        "calls": total_calls,
        "calls_partial": calls_missing_any,
        "models": len(models),
        "tiers": len(tiers),
    }


