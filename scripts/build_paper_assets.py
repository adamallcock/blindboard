    acc = lambda arm, m, t, e: arm[(m, t, e)]["mean"]
    v["effortgapvisible"] = f"{round(100 * (acc(legacy_cells, 'gpt-5.6-luna', 't6_gauntlet', 'max') - acc(legacy_cells, 'gpt-5.6-sol', 't6_gauntlet', 'medium'))):.0f}"
    v["effortgapretained"] = f"{round(100 * (acc(cells, 'gpt-5.6-luna', 't6_gauntlet', 'max') - acc(cells, 'gpt-5.6-sol', 't6_gauntlet', 'medium'))):.0f}"
    v["spreadvisible"] = f"{100 * (acc(legacy_cells, 'gpt-5.6-sol', 't11_maelstrom', 'max') - acc(legacy_cells, 'gpt-5.6-luna', 't11_maelstrom', 'max')):.1f}"
