    worst = min(diffs, key=diffs.get)
    v["solperpwithoutworst"] = f"{round(-100 * (sum(diffs.values()) - diffs[worst]) / (len(diffs) - 1)):.0f}"
    worst_doc = _episode_doc(r_by[worst].path)
    v["solperpworstded"] = str((worst_doc["result"].get("diagnostics") or {}).get("deducible_at_guess"))
    v["solperpworstboard"] = str(worst_doc["result"].get("board_n"))
    big = [pair_by[("gpt-5.6-sol", t, "max")] for t in ("t9_numrow", "t9_macbook")]
    v["solflipsvwon"] = str(sum(r["flips_visible"][0] for r in big))
    v["solflipsvcalls"] = str(sum(r["flips_visible"][1] for r in big))
    v["solflipsrwon"] = str(sum(r["flips_retained"][0] for r in big))
    v["solflipsrcalls"] = str(sum(r["flips_retained"][1] for r in big))
