def _sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generator_git_commit() -> dict:
    """The commit the manifest was generated at, plus whether any tracked
    file had uncommitted changes. A frozen snapshot that cannot name its
    generator is not frozen. Untracked files (build logs, another session's
    scratch files in this shared checkout) do not make the generator dirty."""
    def _git(*args: str) -> str | None:
        try:
            done = subprocess.run(
                ["git", *args], cwd=REPO_ROOT, capture_output=True, text=True, timeout=30
            )
        except (OSError, subprocess.SubprocessError):
            return None
        return done.stdout.strip() if done.returncode == 0 else None

    commit = _git("rev-parse", "HEAD")
    status = _git("status", "--porcelain", "--untracked-files=no")
    return {
        "commit": commit,
        "dirty": None if status is None else bool(status),
    }


def _manifest_entry(record: RunDirRecord) -> dict:
    per_file_hashes = [_sha256_file(p) for p in record.seed_paths]
    usage = {"input_tokens": 0, "output_tokens": 0}
    api_calls = 0
    for path in record.seed_paths:
        result = json.loads(path.read_text(encoding="utf-8"))["result"]
        episode_usage = result.get("usage") or {}
        usage["input_tokens"] += episode_usage.get("input_tokens") or 0
        usage["output_tokens"] += episode_usage.get("output_tokens") or 0
        api_calls += result.get("api_calls") or 0
    cost = usage_cost(record.model, usage)
    return {
        "tree": record.tree,
        "dir_name": record.name,
        "status": record.status,
        "model": record.model,
        "tier": record.tier,
        "effort": record.effort,
        "summary_sha256": (
            _sha256_file(record.path / "summary.json") if record.has_summary else None
        ),
        "seed_file_names_sorted": [p.name for p in record.seed_paths],
        "seed_files_sha256": hashlib.sha256(
            "".join(per_file_hashes).encode("ascii")
        ).hexdigest(),
        "episodes": len(record.seed_paths),
        "api_calls": api_calls,
        "cost_usd_list_price": None if cost is None else round(cost, 6),
    }


def build_snapshot_manifest(
    results_dir: Path, extra_trees: Sequence[Path] = ()
) -> dict:
    """Hash-pin EVERY run directory in every covered tree.

    Each entry is classified `included` (has a summary.json, so it is
    assignable to a cell) or `excluded-no-summary` (a completed-but-unsummarized
    partial). Both are pinned: the K3 finding was that skipping the latter let a
    "frozen" snapshot silently omit real, completed, already-paid-for episodes.
    The generator's git commit is recorded so the manifest names its own
    provenance.
    """
    runs: list[dict] = []
    for tree in [results_dir, *extra_trees]:
        runs.extend(_manifest_entry(record) for record in scan_run_dirs(tree))
    runs.sort(key=lambda entry: (entry["tree"], entry["dir_name"]))
    return {
        "generated_by": "scripts/build_paper_assets.py --freeze",
        "generator_git": generator_git_commit(),
        "trees": sorted({entry["tree"] for entry in runs}),
        "included": sum(1 for entry in runs if entry["status"] == "included"),
        "excluded_no_summary": sum(
            1 for entry in runs if entry["status"] == "excluded-no-summary"
        ),
        "runs": runs,
    }


def enforce_snapshot_freeze(
    results_dir: Path, manifest_path: Path, extra_trees: Sequence[Path] = ()
) -> None:
    """Fail closed (SystemExit) when the results trees do not match the frozen
    manifest exactly: manifest missing, any manifested dir missing, any hash or
    classification differing, or ANY unlisted run dir present — with or without
    a summary.json. A completed partial is evidence; an unlisted one means the
    named snapshot no longer describes what is on disk.

    Only status and the three hash fields are compared. The rest of a manifest
    entry (episode counts, api calls, prices, model ids) is an audit trail: a
    pricing-registry update must not be able to trip an integrity check."""
    if not manifest_path.exists():
        raise SystemExit(
            f"SNAPSHOT_FROZEN is True but {manifest_path} does not exist. "
            "Run `python scripts/build_paper_assets.py --freeze` to write the "
            "snapshot manifest, then re-run."
        )
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    current = {
        (entry["tree"], entry["dir_name"]): entry
        for entry in build_snapshot_manifest(results_dir, extra_trees)["runs"]
    }
    problems: list[str] = []
    for entry in manifest["runs"]:
        key = (entry.get("tree"), entry["dir_name"])
        shown = f"{key[0]}/{key[1]}" if key[0] else key[1]
        observed = current.pop(key, None)
        if observed is None:
            problems.append(f"manifested run dir missing: {shown}/")
            continue
        if observed["status"] != entry.get("status"):
            problems.append(
                f"{shown}/ classification changed: manifest says "
                f"{entry.get('status')}, tree says {observed['status']}"
            )
        if observed["summary_sha256"] != entry.get("summary_sha256"):
            problems.append(f"{shown}/summary.json differs from the frozen manifest")
        if observed["seed_file_names_sorted"] != entry["seed_file_names_sorted"]:
            problems.append(f"{shown}/ seed file set differs from the frozen manifest")
        elif observed["seed_files_sha256"] != entry["seed_files_sha256"]:
            problems.append(f"{shown}/ seed file contents differ from the frozen manifest")
    for key in sorted(current):
        shown = f"{key[0]}/{key[1]}" if key[0] else key[1]
        problems.append(f"unmanifested run dir ({current[key]['status']}): {shown}/")
    if problems:
        raise SystemExit(
            "Snapshot freeze check FAILED (SNAPSHOT_FROZEN=True); refusing to "
            "build paper assets from a drifted results tree:\n  - "
            + "\n  - ".join(problems)
        )


def enforce_freeze_if_frozen(results_dir: Path) -> None:
    """The one freeze entry point. Called by this builder AND by
    scripts/make_figures.py so tables and figures cannot be frozen apart."""
    if not SNAPSHOT_FROZEN:
        return
    enforce_snapshot_freeze(
        results_dir,
        SNAPSHOT_MANIFEST_PATH,
        [REPO_ROOT / tree for tree in SNAPSHOT_EXTRA_TREES],
    )


