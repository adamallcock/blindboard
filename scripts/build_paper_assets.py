WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine",
         "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen", "sixteen",
         "seventeen", "eighteen", "nineteen", "twenty"]


def word(n: int, capital: bool = False) -> str:
    text = WORDS[n] if 0 <= n < len(WORDS) else str(n)
    return text.capitalize() if capital else text


def dec2(x: float) -> str:
    """Two decimals, half-up on the decimal value, no leading zero: .355 -> .36."""
    from decimal import ROUND_HALF_UP, Decimal

    text = str(Decimal(str(x)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))
    return text.replace("0.", ".", 1) if text.lstrip("-").startswith("0.") else text


def floor2(x: float) -> str:
    """A floor at two decimals, for 'X or above' claims: .828 -> .82."""
    return fmt3(math.floor(100 * x + 1e-9) / 100)[:-1]


