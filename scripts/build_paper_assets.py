# The stress board: every turn ends with a derangement of three announced keys.
FLIP_TIERS = ("t7_perpetual", "t11_maelstrom")
# The generated evidence reads these as well as the primary tree.
DIAGNOSTICS_TREE = "results/diagnostics"
HELDOUT_CALIBRATION_DIR = "results/calibration-heldout"
# A pair passes when the next billed prompt grows by at least this share of
# the previous call's output, after the new user text (at CHARS_PER_TOKEN) is
# taken off. The corpus median is 1.00; a dropped reasoning block sits near 0.
RETENTION_PASS_SHARE = 0.5
CHARS_PER_TOKEN = 3.5
ROUTE_MECHANISM = {
    "OpenAI": "encrypted items",
    "Anthropic": "signed thinking",
    "Google": "thought signatures",
    "OpenRouter": "reasoning details + tool",
}


def _episode_doc(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _final_address_of(doc: dict) -> dict[int, str]:
    """Physical position -> the address it carries at the guess, after every
    relabel (the guess and the final layout are keyed by these)."""
    board = BOARDS[doc["result"]["config"]["board"]]
    groups = {label: idx for label, idx, _ in board.column_groups}
    addr_to_phys = list(range(board.n))
    for record in doc.get("records") or []:
        swap = record.get("relabel")
        if swap:
            for x, y in zip(groups[swap["a"]], groups[swap["b"]]):
                addr_to_phys[x], addr_to_phys[y] = addr_to_phys[y], addr_to_phys[x]
    return {addr_to_phys[i]: board.addresses[i] for i in range(board.n)}


def final_flip(doc: dict) -> bool | None:
    """Whether the guess called the last rotation's coin flip right, or None
    when there was no flip to call. A derangement of three keys leaves
    their symbols in one of two arrangements, the two 3-cycles of the
    arrangement before it. The flip was called when the guess is one of
    those two, so only the coin decided between them. A guess with the
    right symbols in any other arrangement (the keys as they stood before
    the rotation, or two of them swapped) is wrong under both outcomes and
    makes no call."""
    arrangement = final_rotation(doc)
    if arrangement is None:
        return None
    before, after, guess = arrangement
    a, b, c = before
    if guess not in ([c, a, b], [b, c, a]):
        return None
    return guess == after


def final_rotation(doc: dict) -> tuple[list, list, list] | None:
    """The symbols on the last rotation's three keys before it, after it,
    and in the guess, in physical-key order; None when the last rotation
    did not derange exactly three keys or there is no guess."""
    result = doc["result"]
    records = doc.get("records") or []
    if (result.get("config") or {}).get("dual") or not records or result.get("guess") is None:
        return None
    rotation = records[-1].get("rotation") or {}
    positions = rotation.get("positions") or []
    if len(positions) != 3:
        return None
    moved_to = {int(src): dst for src, dst in rotation["permutation"].items()}
    address_of = _final_address_of(doc)
    final = result.get("final_layout") or {}
    after = [final.get(address_of[p]) for p in positions]
    before = [final.get(address_of[moved_to[p]]) for p in positions]
    if None in after or None in before:
        return None
    return before, after, [result["guess"].get(address_of[p]) for p in positions]


def flip_neutral_accuracy(doc: dict) -> float:
    """Board accuracy with a called final flip scored at its expectation,
    1.5 of its three keys, instead of 0 or 3: the same board without the
    luck of the last coin flip. A called flip that lost scored 0 of the
    three keys, because the two arrangements differ on all three."""
    result = doc["result"]
    called = final_flip(doc)
    if called is None:
        return result["board_accuracy"]
    n = result.get("board_n") or len(result["final_layout"])
    return result["board_accuracy"] + (1.5 - (3 if called else 0)) / n


def final_flip_draws(cells: dict[tuple[str, str, str], dict]) -> dict[str, int]:
    """Called flips on the stress-board tiers grouped by the draw they called.
    Episodes on one seed meet the same final rotation when they reach the
    same turn, so several models can call one draw: the calls are not
    independent trials."""
    draws: dict[tuple, int] = {}
    for (_model, tier, _effort), cell in cells.items():
        if tier not in FLIP_TIERS:
            continue
        for ep in cell["episodes"]:
            doc = _episode_doc(ep.path)
            if final_flip(doc) is None:
                continue
            last = doc["records"][-1]
            key = (tier, doc["result"].get("seed"), last["turn"], json.dumps(last["rotation"], sort_keys=True))
            draws[key] = draws.get(key, 0) + 1
    return {"draws": len(draws), "calls": sum(draws.values()), "max_calls_per_draw": max(draws.values(), default=0)}


def final_flip_stats(cells: dict[tuple[str, str, str], dict]) -> dict[tuple[str, str], list[int]]:
    """[called right, callable] per (model, effort) on the stress-board tiers."""
    per: dict[tuple[str, str], list[int]] = {}
    for (model, tier, effort), cell in cells.items():
        if tier not in FLIP_TIERS:
            continue
        row = per.setdefault((model, effort), [0, 0])
        for ep in cell["episodes"]:
            called = final_flip(_episode_doc(ep.path))
            if called is not None:
                row[1] += 1
                row[0] += int(called)
    return per


def binomial_upper_tail(n: int, k: int) -> float:
    """P(Binomial(n, 1/2) >= k)."""
    return sum(math.comb(n, i) for i in range(max(k, 0), n + 1)) / 2**n


def retention_growth(cells: dict[tuple[str, str, str], dict]) -> dict[str, dict]:
    """Per model over the canonical population: consecutive call pairs in
    which the earlier call's output (its reasoning included) re-entered the
    next billed prompt. A call cut off at the output limit, or ended by a
    DeepSeek inert-tool call, is not replayed, so the pair after it is
    counted apart; a turn re-sent to another host is compared on the
    attempt that was kept.

    Growth of half the earlier output can come from its visible reply
    alone, so the reasoning check goes further: on pairs whose earlier
    call reasoned, the growth left after the new user text and the earlier
    visible reply (output less reasoning tokens) has to cover half of that
    reasoning. ``reasoning_shares`` keeps each pair's covered share, and
    ``reasoning_fail_max`` the longest reasoning among the pairs that fail."""
    out: dict[str, dict] = {}
    for (model, _tier, _effort), cell in cells.items():
        row = out.setdefault(model, {"pairs": 0, "passed": 0, "after_incomplete": 0, "reasoned": 0,
                                     "reasoning_passed": 0, "reasoning_fail_max": 0, "reasoning_shares": []})
        for ep in cell["episodes"]:
            prev: dict | None = None
            user_chars = 0
            for msg in _episode_doc(ep.path)["transcript"]:
                role = msg.get("role")
                if role == "user":
                    user_chars += len(msg.get("text") or "")
                    continue
                if role != "assistant":
                    continue
                if prev is not None:
                    # A turn re-sent to another host records the dropped
                    # attempt's usage too; only the kept attempt is replayed.
                    dropped = (prev.get("harness") or {}).get("rerouted") or []

                    def kept(key: str) -> int:
                        return ((prev.get("usage") or {}).get(key) or 0) - sum(
                            ((attempt.get("usage") or {}).get(key) or 0) for attempt in dropped
                        )

                    prior_out = kept("output_tokens")
                    # The current turn's own re-sent attempts are billed in
                    # its usage too; its prompt is the kept attempt's.
                    resent_in = sum(
                        ((attempt.get("usage") or {}).get("input_tokens") or 0)
                        for attempt in (msg.get("harness") or {}).get("rerouted") or []
                    )
                    if (prev.get("harness") or {}).get("incomplete"):
                        row["after_incomplete"] += 1
                    elif prior_out > 0:
                        grown = ((msg.get("usage") or {}).get("input_tokens") or 0) - resent_in - kept("input_tokens")
                        beyond_user = grown - user_chars / CHARS_PER_TOKEN
                        row["pairs"] += 1
                        row["passed"] += int(beyond_user / prior_out >= RETENTION_PASS_SHARE)
                        prior_reasoning = kept("reasoning_tokens")
                        if prior_reasoning > 0:
                            covered = (beyond_user - (prior_out - prior_reasoning)) / prior_reasoning
                            row["reasoned"] += 1
                            row["reasoning_shares"].append(covered)
                            if covered >= RETENTION_PASS_SHARE:
                                row["reasoning_passed"] += 1
                            else:
                                row["reasoning_fail_max"] = max(row["reasoning_fail_max"], prior_reasoning)
                prev = msg
                user_chars = 0
    return out


def recall_probe(repo_root: Path = REPO_ROOT) -> dict[str, dict]:
    """Per model, its latest recall-probe run counted from the trials. Per
    variant: trials attempted; those whose first-turn summary states N, the
    only ones that can be scored; of those, the trials where both retained
    forks replied, where they answered for that N, and where they declined;
    trials the provider refused (stop reason ``refusal``); the visible-only
    control's matches; and the stated trials whose summary names more than
    one candidate N (a reply then counts if it fits any of them), with how
    many of those matched. Also the run's list cost."""
    latest: dict[str, Path] = {}
    for path in sorted((repo_root / DIAGNOSTICS_TREE).glob("retention-recall-probe-*/summary.json")):
        doc = json.loads(path.read_text(encoding="utf-8"))
        if "variants" in doc:
            latest[doc["model"]] = path.parent
    out: dict[str, dict] = {}
    for model, run_dir in latest.items():
        summary = json.loads((run_dir / "summary.json").read_text(encoding="utf-8"))
        variants: dict[str, dict[str, int]] = {}
        for line in (run_dir / "trials.jsonl").read_text(encoding="utf-8").splitlines():
            trial = json.loads(line)
            row = variants.setdefault(trial["variant"], dict.fromkeys(
                ("attempted", "stated", "complete", "matched", "abstained", "refused", "control_matched",
                 "multi", "multi_matched"), 0))
            row["attempted"] += 1
            verdict = trial.get("verdict") or {}
            if verdict.get("leaked") or not verdict.get("summary_n"):
                continue
            row["stated"] += 1
            complete = verdict.get("retained_complete", "r1" in trial and "r2" in trial)
            refused = any("refusal" in err for name, err in (trial.get("branch_errors") or {}).items()
                          if name in ("r1", "r2"))
            row["complete"] += int(complete)
            row["matched"] += int(bool(verdict.get("matches_summary_n")))
            row["abstained"] += int(complete and not verdict.get("retained_answered"))
            row["refused"] += int(refused)
            row["control_matched"] += int(bool(verdict.get("control_matches_summary_n")))
            if len(verdict["summary_n"]) > 1:
                row["multi"] += 1
                row["multi_matched"] += int(bool(verdict.get("matches_summary_n")))
        out[model] = {"variants": variants, "cost_usd_list_price": summary["cost_usd_list_price"]}
    return out


def reply_outcomes(cells: dict[tuple[str, str, str], dict], prefix: str = "openrouter/deepseek/") -> dict[str, dict[str, int]]:
    """Calls per model that produced no action: an inert-tool call, a reply
    that stopped after reasoning, or one cut off at the output cap."""
    out: dict[str, dict[str, int]] = {}
    for (model, _tier, _effort), cell in cells.items():
        if not model.startswith(prefix):
            continue
        row = out.setdefault(model, {"calls": 0, "tool_call": 0, "reasoning_only": 0, "capped": 0})
        for ep in cell["episodes"]:
            for msg in _episode_doc(ep.path)["transcript"]:
                if msg.get("role") != "assistant":
                    continue
                row["calls"] += 1
                if (msg.get("harness") or {}).get("incomplete") == "tool_call":
                    row["tool_call"] += 1
                elif not (msg.get("text") or "").strip():
                    capped = msg.get("stop_reason") in ("length", "max_tokens")
                    row["capped" if capped else "reasoning_only"] += 1
    return out


def schedule_text_changed(tier: str) -> bool:
    """bb-r1 told every announced tier that rotations eventually stop; bb-r2
    kept that text where it is true and says so only there."""
    from blindboard.prompts import schedule_tail

    return "ENTIRE game" in schedule_tail(TIERS[tier])


def prompt_version_confound(pairs: list[dict], legacy_cells: dict[tuple[str, str, str], dict]) -> dict[str, object]:
    """Paired cells whose earlier-campaign episodes ran the bb-r1 prompt, and
    the subset on tiers where bb-r1's text differs from bb-r2's."""
    old_cells: list[dict] = []
    for r in pairs:
        cell = legacy_cells[(r["model"], r["tier"], r["effort"])]
        by_seed = {ep.seed: ep for ep in cell["episodes"]}
        old = sum(
            1 for s in r["seeds"]
            if _episode_doc(by_seed[s].path)["result"].get("prompt_version") != "bb-r2"
        )
        if old:
            old_cells.append({**r, "old_prompt_pairs": old, "text_changed": schedule_text_changed(r["tier"])})
    changed = [r for r in old_cells if r["text_changed"]]
    return {
        "cells": len(old_cells),
        "changed_cells": len(changed),
        "changed_pairs": sum(r["old_prompt_pairs"] for r in changed),
        "changed": changed,
    }


def harness_cost_stats(pairs: list[dict], cells: dict, legacy_cells: dict) -> dict[str, float]:
    """List cost of the paired seeds under each harness, and the median
    per-cell ratio of billed input tokens (retained over visible)."""
    cost_r = cost_v = 0.0
    ratios: list[float] = []
    for r in pairs:
        key = (r["model"], r["tier"], r["effort"])
        r_by = {ep.seed: ep for ep in cells[key]["episodes"]}
        v_by = {ep.seed: ep for ep in legacy_cells[key]["episodes"]}
        cost_r += sum(r_by[s].cost_usd for s in r["seeds"])
        cost_v += sum(v_by[s].cost_usd for s in r["seeds"])
        in_r = sum(r_by[s].input_tokens for s in r["seeds"])
        in_v = sum(v_by[s].input_tokens for s in r["seeds"])
        if in_r and in_v:
            ratios.append(in_r / in_v)
    ratios.sort()
    mid = len(ratios) // 2
    median = (ratios[mid] if len(ratios) % 2 else (ratios[mid - 1] + ratios[mid]) / 2) if ratios else 0.0
    return {"retained": cost_r, "visible": cost_v, "input_ratio_median": median}


def _latest_calibration(calibration_dir: Path, agent: str) -> dict[str, tuple[float, float]]:
    latest: dict[str, tuple[float, float]] = {}
    for path in sorted(calibration_dir.glob("calibration-*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        for tier, agents in (data.get("table") or {}).items():
            entry = (agents or {}).get(agent) or {}
            if entry.get("board_accuracy_mean") is not None:
                latest[tier] = (entry["board_accuracy_mean"], entry.get("board_accuracy_sem") or 0.0)
    return latest


def heldout_calibration(repo_root: Path = REPO_ROOT) -> dict[str, object] | None:
    """Each tier's certificate against the same agent on fresh seeds, for
    every tier with a held-out run."""
    heldout_dir = repo_root / HELDOUT_CALIBRATION_DIR
    files = sorted(heldout_dir.glob("calibration-*.json"))
    if not files:
        return None
    meta = json.loads(files[-1].read_text(encoding="utf-8"))
    # As load_calibration_best: the planner where it ran, else the reference.
    cal = repo_root / "results" / "calibration"
    certs = {**_latest_calibration(cal, "reference"), **_latest_calibration(cal, "planner")}
    held = {**_latest_calibration(heldout_dir, "reference"), **_latest_calibration(heldout_dir, "planner")}
    rows = []
    for tier, (mean, sem) in sorted(held.items()):
        if tier not in certs:
            continue
        cert, cert_sem = certs[tier]
        se = (sem**2 + cert_sem**2) ** 0.5
        rows.append({"tier": tier, "certificate": cert, "heldout": mean, "gap": mean - cert,
                     "z": (mean - cert) / se if se else 0.0, "ceiling": CEILINGS.get(tier)})
    worst = max(rows, key=lambda r: abs(r["gap"]))
    above = [r for r in rows if r["ceiling"] is not None and r["certificate"] > r["ceiling"]]
    return {
        "seed_start": meta.get("seed_start", 0), "seeds": meta.get("seeds"), "rows": rows,
        "worst": worst, "max_abs_z": max(abs(r["z"]) for r in rows),
        "above": above,
        "above_back": sum(1 for r in above if r["heldout"] <= r["ceiling"] + 0.0005),
    }


def retention_table(cells: dict[tuple[str, str, str], dict], repo_root: Path = REPO_ROOT) -> str:
    """Per model: how its reasoning is carried, the corpus check that it
    re-entered the next prompt, and the recall probe where one was run."""
    growth = retention_growth(cells)
    probe = recall_probe(repo_root)
    lines = [
        GENERATED_HEADER,
        "\\begin{tabular}{@{}l l r r r r r@{}}",
        "\\toprule",
        " & \\multicolumn{2}{c}{(a) Billing check} & \\multicolumn{4}{c}{(b) Recall probe} \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(l){4-7}",
        "Model & Carried as & Re-entered & $N$ stated & May decline & Must answer & Control \\\\",
        "\\midrule",
    ]
    models = sorted(growth, key=lambda m: MODEL_ORDER.get(m, 99))
    for model in models:
        g = growth[model]
        route = route_of(model)
        doc = probe.get(model)
        if doc:
            esc, frc = doc["variants"].get("escape", {}), doc["variants"].get("forced", {})

            def both(key: str) -> int:
                return esc.get(key, 0) + frc.get(key, 0)

            probe_cols = (
                f"{both('stated')}/{both('attempted')} & "
                f"{esc.get('matched', 0)}/{esc.get('complete', 0)} & "
                f"{frc.get('matched', 0)}/{frc.get('complete', 0)} & "
                f"{both('control_matched')}/{both('stated')}"
            )
        else:
            probe_cols = "\\multicolumn{4}{c}{not probed}"
        lines.append(
            f"{model_mark(model)}\\texttt{{{latex_escape(model.split('/')[-1])}}} & "
            f"{ROUTE_MECHANISM.get(route, route)} & {_grouped(g['reasoning_passed'])}/{_grouped(g['reasoned'])} & {probe_cols} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    return "\n".join(lines)


def evidence_macros(
    cells: dict[tuple[str, str, str], dict],
    legacy_cells: dict[tuple[str, str, str], dict],
    pairs: list[dict],
    repo_root: Path = REPO_ROOT,
) -> list[str]:
    """Macros for the numbers the harness, validation and comparison
    sections quote, so no count is typed by hand."""
    lines = ["% ---- EVIDENCE: retention, recall probe, flips, confounds ----------"]

    def macro(name: str, value: object) -> None:
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    growth = retention_growth(cells)
    by_route: dict[str, list[int]] = {}
    for model, g in growth.items():
        row = by_route.setdefault(route_of(model), [0, 0])
        row[0] += g["passed"]
        row[1] += g["pairs"]
    macro("retentionpairs", _grouped(sum(g["pairs"] for g in growth.values())))
    macro("retentionpassed", _grouped(sum(g["passed"] for g in growth.values())))
    macro("retentionafterincomplete", sum(g["after_incomplete"] for g in growth.values()))
    # The reasoning check: pairs whose earlier call reasoned, those whose
    # growth beyond the user text and visible reply covers half of it, the
    # longest reasoning among the rest, and the median covered share.
    reasoned = sum(g["reasoned"] for g in growth.values())
    reasoning_passed = sum(g["reasoning_passed"] for g in growth.values())
    shares = sorted(s for g in growth.values() for s in g["reasoning_shares"])
    macro("retentionreasonedpairs", _grouped(reasoned))
    macro("retentionreasoningpassed", _grouped(reasoning_passed))
    macro("retentionreasoningfailed", word(reasoned - reasoning_passed))
    macro("retentionreasoningfailmax", max((g["reasoning_fail_max"] for g in growth.values()), default=0))
    macro("retentionreasoningmedianpct", f"{100 * statistics.median(shares):.0f}" if shares else "0")
    for route, name in (("OpenAI", "openai"), ("Anthropic", "anthropic"), ("Google", "gemini"), ("OpenRouter", "deepseek")):
        passed, total = by_route.get(route, [0, 0])
        macro(f"retention{name}pairs", _grouped(total))
        macro(f"retention{name}passed", _grouped(passed))

    probe = recall_probe(repo_root)

    def probe_sum(key: str, variant: str | None = None, models: list[str] | None = None) -> int:
        return sum(
            v.get(key, 0)
            for m, d in probe.items() if models is None or m in models
            for name, v in d["variants"].items() if variant is None or name == variant
        )

    openai = [m for m in probe if m.startswith("gpt-")]
    others = [m for m in probe if not m.startswith("claude-")]
    macro("recallmodels", word(len(probe)))
    macro("recallopenaimodels", word(len(openai)))
    macro("recalltrials", _grouped(probe_sum("attempted")))
    macro("recallstated", _grouped(probe_sum("stated")))
    macro("recallcost", _usd(sum(d["cost_usd_list_price"] for d in probe.values())))
    for variant, name in (("escape", "maydecline"), ("forced", "must")):
        # Every model but opus5.5, which declines whenever it may.
        macro(f"recall{name}matched", _grouped(probe_sum("matched", variant, others)))
        macro(f"recall{name}complete", _grouped(probe_sum("complete", variant, others)))
        # Missing-data bounds on exact recovery over every OpenAI trial: each
        # trial whose summary states no N counted as a miss, then as a hit.
        attempted = probe_sum("attempted", variant, openai)
        matched = probe_sum("matched", variant, openai)
        unstated = attempted - probe_sum("stated", variant, openai)
        macro(f"recallopenai{name}low", matched)
        macro(f"recallopenai{name}high", matched + unstated)
        macro(f"recallopenai{name}trials", attempted)
    macro("recallcontrolstated", _grouped(probe_sum("stated")))
    macro("recallcontrolmatched", probe_sum("control_matched"))
    macro("recallmulticandidate", word(probe_sum("multi")))
    macro("recallmulticandidatematched", word(probe_sum("multi_matched")))
    for model, name in (("claude-opus-5-5", "opus"), ("gemini/gemini-3.8-flash", "gemini")):
        if model not in probe:
            continue
        macro(f"recall{name}trials", probe_sum("attempted", None, [model]))
        macro(f"recall{name}refused", probe_sum("refused", None, [model]))
        for variant, vname in (("escape", "maydecline"), ("forced", "must")):
            macro(f"recall{name}{vname}attempted", probe_sum("attempted", variant, [model]))
            macro(f"recall{name}{vname}matched", probe_sum("matched", variant, [model]))
            macro(f"recall{name}{vname}complete", probe_sum("complete", variant, [model]))
            macro(f"recall{name}{vname}abstained", probe_sum("abstained", variant, [model]))
            macro(f"recall{name}{vname}refused", probe_sum("refused", variant, [model]))

    outcomes = reply_outcomes(cells)
    for model, name in (("openrouter/deepseek/deepseek-v4-flash", "dsflash"),
                        ("openrouter/deepseek/deepseek-v4.1-flash", "dsfouroneflash"),
                        ("openrouter/deepseek/deepseek-v4-pro", "dspro")):
        o = outcomes.get(model, {"calls": 0, "tool_call": 0, "reasoning_only": 0, "capped": 0})
        macro(f"{name}calls", o["calls"])
        macro(f"{name}toolcalls", o["tool_call"])
        macro(f"{name}reasoningonly", o["reasoning_only"])
        macro(f"{name}capped", o["capped"])

    flips = final_flip_stats(cells)
    pair_keys = [("gpt-6-astra", "max"), ("gpt-6-sol", "max")]
    right_all = sum(v[0] for v in flips.values())
    calls_all = sum(v[1] for v in flips.values())
    right_pair = sum(flips.get(k, [0, 0])[0] for k in pair_keys)
    calls_pair = sum(flips.get(k, [0, 0])[1] for k in pair_keys)
    draws = final_flip_draws(cells)
    macro("flipconfigs", sum(1 for v in flips.values() if v[1]))
    macro("flipallright", right_all)
    macro("flipallcalls", calls_all)
    # No roster-wide binomial tail: the calls share draws (see final_flip_draws).
    macro("flipalldraws", draws["draws"])
    macro("flipmaxcallsperdraw", word(draws["max_calls_per_draw"]))
    macro("flipotherright", right_all - right_pair)
    macro("flipothercalls", calls_all - calls_pair)
    macro("flippairright", right_pair)
    macro("flippaircalls", calls_pair)
    macro("flippairp", fmt_dec(binomial_upper_tail(calls_pair, right_pair)))
    for key, name in zip(pair_keys, ("astra", "gptsixsol")):
        macro(f"flip{name}right", flips.get(key, [0, 0])[0])
        macro(f"flip{name}calls", flips.get(key, [0, 0])[1])

    sys.path.insert(0, str(REPO_ROOT / "scripts"))
    from derangement_structure_audit import run_audit

