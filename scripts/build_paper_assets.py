def short_model(model: str) -> str:
    """Strip the gpt-5.4-/gpt-5.6- prefix, e.g. 'gpt-5.6-luna' -> 'luna'."""
    for prefix in MODEL_PREFIXES:
        if model.startswith(prefix):
            return model[len(prefix) :]
    return model


def latex_escape(value: object) -> str:
    text = str(value)
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in text)


def fmt_dec(value: float, decimals: int = 3) -> str:
    """Fixed-decimal string with the leading zero dropped, e.g. .875, -.056.

    Values >= 1 (e.g. a perfect 1.000 mean) are left as-is since there is no
    leading zero to drop.
    """
    text = f"{value:.{decimals}f}"
    if text.startswith("0."):
        return text[1:]
    if text.startswith("-0."):
        return "-" + text[2:]
    return text


def fmt_money(value: float) -> str:
    return f"\\${value:.2f}"


