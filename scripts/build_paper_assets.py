#!/usr/bin/env python3
"""Generate paper-ready LaTeX table/macro assets from results/llm/*, the test
suite, and calibration snapshots.

Follows the house style of the sibling obviousbench/copybench repo's
scripts/paper_arxiv/build_paper_assets.py: booktabs/tabularx tables with a
"Do not hand-edit" header. Deterministic given an unchanged repo state, so
repeated invocations produce byte-identical output.

Writes:
  paper/tables/main_results.tex      all LLM game runs, one row per
                                      (model, tier, effort)
  paper/tables/effort_sweep.tex      gauntlet-only medium vs. max comparison
  paper/tables/violations.tex        protocol-failure taxonomy by route
  paper/tables/readiness_gates.tex   computed PASS/WARN/FAIL gates
  paper/tables/snapshot_macros.tex   \\newcommand snapshot numbers

ONE canonicalization rule, ONE population (fix for M5). `canonical_selection()`
is the single selection function behind every output: it deduplicates episodes
by (cell, seed) with later-run-dir-wins and returns the SELECTED episodes
themselves. Tables, figures, macros and the violation taxonomy all read that
one result — scripts/make_figures.py imports it rather than re-aggregating
run directories, so a plotted cell and its table cell cannot disagree.

Cost follows the selection: a cell's printed cost is the list-price cost of the
episodes that cell actually scores, priced per episode from result.usage.
Spend on superseded re-runs is real money but not this cell's cost, so it is
reported separately as campaign spend (see `campaign_spend()`).

results/llm/*/summary.json is the source of truth for which (model, tier,
effort) cells exist. A run directory that only has seed*.json files but no
summary.json (e.g. a crashed run that never reached the summary-write step)
is NOT assigned to any cell and is excluded from every scored aggregate; it
is still identified from its directory name, hash-pinned in the snapshot
manifest as `excluded-no-summary`, priced into campaign spend, and reported
back to the caller as an anomaly — never silently merged, never invisible.
"""

