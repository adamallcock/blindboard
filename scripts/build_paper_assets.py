EFFORT_MARK = {"low": "l", "medium": "m", "high": "h", "xhigh": "x", "max": "M"}


def mean_sem(mean: float, sem: float) -> str:
    """A cell mean with its SEM set small beside it: 1.000 ±.000."""
    return f"{fmt3(mean)}{{\\scriptsize\\,$\\pm${fmt3(sem)}}}"


def config_label(model: str, effort: str) -> str:
    """Swatch, icon, the model identifier without its route prefix, and the effort."""
    return f"{model_mark(model)}\\texttt{{{latex_escape(model.split('/')[-1])}}} / {latex_escape(effort)}"


def pooled_mark(note: str | None) -> str:
    """'pooled medium+high' -> 'mh': the requested labels a single-mode cell pooled."""
    if not note or not note.startswith("pooled "):
        return ""
    return "".join(EFFORT_MARK.get(label, label[:1]) for label in note[len("pooled "):].split("+"))


def expected_n(tier: str) -> int:
    return 20 if tier == "t2_announced" else 5


# The full matrices run in blocks by board size, with horizontal tier names.
GRID_BLOCKS = (
    ("12 keys", ("fingers12",)),
    ("26 keys", ("qwerty26",)),
    ("39 and 47 keys", ("qwerty39", "macbook47")),
)


def cell_grid_table(cells: dict[tuple[str, str, str], dict]) -> str:
    """Every (model, effort) configuration against every tier it played, in
    blocks by board size so the tier names can run horizontally: mean board
    accuracy, with its SEM on the line below. Single-mode cells carry the
    requested labels they pooled; a cell whose n breaks the 20-on-announced,
    5-elsewhere rule carries its n; a dash was not run."""
    tiers = [t for t in TIERS if any(key[1] == t for key in cells)]
    configs = sorted(
        {(m, e) for (m, _t, e) in cells},
        key=lambda c: (MODEL_ORDER.get(c[0], 99), EFFORT_ORDER.get(c[1], 99), c[0]),
    )
    lines = [GENERATED_HEADER]
    for title, boards in GRID_BLOCKS:
        block = [t for t in tiers if TIERS[t].board in boards]
        rows = [(m, e) for (m, e) in configs if any(cells.get((m, t, e)) for t in block)]
        if not rows:
            continue
        if len(lines) > 1:
            lines.append("\\par\\medskip")
        header = " & ".join(f"\\texttt{{{latex_escape(t.split('_', 1)[1])}}}" for t in block)
        lines.extend([
            f"\\begin{{tabular}}{{@{{}}l {'r' * len(block)}@{{}}}}",
            "\\toprule",
            f"\\textit{{{title}}} & {header} \\\\",
            "\\midrule",
        ])
        for index, (model, effort) in enumerate(rows):
            means, sems = [], []
            for tier in block:
                cell = cells.get((model, tier, effort))
                if not cell or not cell["n"]:
                    means.append("--")
                    sems.append("")
                    continue
                mark = pooled_mark(cell.get("note"))
                means.append(fmt3(cell["mean"]) + (f"$^{{\\mathrm{{{mark}}}}}$" if mark else ""))
                n_note = f"$_{{n={cell['n']}}}$" if cell["n"] != expected_n(tier) else ""
                sems.append(f"{{\\fontsize{{7}}{{8}}\\selectfont\\color{{black!70}}$\\pm${fmt3(cell['sem'])}{n_note}}}")
            if index:
                lines.append("\\addlinespace[1pt]")
            lines.append(f"{config_label(model, effort)} & {' & '.join(means)} \\\\[-2pt]")
            lines.append(f" & {' & '.join(sems)} \\\\")
        lines.extend(["\\bottomrule", "\\end{tabular}"])
    lines.append("")
    return "\n".join(lines)


