def usage_table(cells: dict[tuple[str, str, str], dict]) -> str:
    """What each model's two tests used: output tokens per episode on each
    stress tier at the route's top effort, and the list cost of each test's
    reported cells."""
    lines = [
        GENERATED_HEADER,
        "\\begin{tabular}{@{}l r r r r r@{}}",
        "\\toprule",
        " & \\multicolumn{2}{c}{Output tokens per episode} & \\multicolumn{3}{c}{List cost} \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(l){4-6}",
        "Model & perpetual & maelstrom & Easy test & Stress test & Both \\\\",
        "\\midrule",
    ]
    for model, _easy, _top, picked in board_cells(cells):
        easy = [c for c in picked[:2] if c]
        stress = [c for c in picked[2:] if c]
        easy_cost = sum(c["cost_usd"] for c in easy)
        stress_cost = sum(c["cost_usd"] for c in stress)
        lines.append(
            f"{model_mark(model)}\\texttt{{{latex_escape(model.split('/')[-1])}}} & "
            f"{_per_episode_k(picked[2])} & {_per_episode_k(picked[3])} & "
            f"{fmt_money(easy_cost) if easy else '--'} & {fmt_money(stress_cost) if stress else '--'} & "
            f"{fmt_money(easy_cost + stress_cost)} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    return "\n".join(lines)


