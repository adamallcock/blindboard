ROUTES = ("OpenAI", "Anthropic", "Google", "OpenRouter")
VIOLATION_CLASSES = (
    ("empty", "Empty reply, no action JSON"),
    ("nonempty", "Non-empty reply, no action JSON"),
    ("unknown", "Unknown key address"),
)
# "TURN 7 of 26." on press turns, "TURN 19: press phase over" on the guess
# turn. Both forms carry the turn number the violation record refers to.
TURN_HEADER_RE = re.compile(r"^TURN (\d+)[: ]")


def route_of(model: str) -> str:
    """API route a run was collected through, from its registry model id."""
    if model.startswith("gemini/"):
        return "Google"
    if model.startswith("openrouter/"):
        return "OpenRouter"
    if model.startswith("claude"):
        return "Anthropic"
    return "OpenAI"


def _retry_replies_by_turn(transcript: list[dict]) -> dict[int, str | None]:
    """Turn number -> the assistant reply to that turn's corrective retry.

    The harness sends exactly one "INVALID ACTION:" corrective prompt per
    turn (the first failure, counted as a retry). A violation is recorded
    only when the reply to THAT prompt also fails, so the reply which the
    violation describes is the assistant message immediately after the
    INVALID ACTION message, on the turn the violation names.
    """
    replies: dict[int, str | None] = {}
    turn: int | None = None
    for index, message in enumerate(transcript):
        if message.get("role") != "user":
            continue
        text = message.get("text") or ""
        header = TURN_HEADER_RE.match(text)
        if header:
            turn = int(header.group(1))
        elif text.startswith("INVALID ACTION:"):
            following = transcript[index + 1] if index + 1 < len(transcript) else None
            replies[turn] = (
                (following or {}).get("text")
                if (following or {}).get("role") == "assistant"
                else None
            )
    return replies


def classify_violation(reason: str, retry_reply: str | None) -> str:
    """One of the VIOLATION_CLASSES keys.

    Address errors are named by the harness's own reason string. Everything
    else is a parse failure, split by whether the model said anything at all
    on the retry: an empty completion (the completion-ceiling failure mode)
    versus prose that carried no action JSON.
    """
    if "Unknown key address" in reason:
        return "unknown"
    return "empty" if not (retry_reply or "").strip() else "nonempty"


def _violations_of(episode: dict, result: dict) -> list[tuple[str, str]]:
    """[(class, reason)] for one loaded episode payload."""
    replies = _retry_replies_by_turn(episode.get("transcript") or [])
    return [
        (classify_violation(v["reason"], replies.get(v["turn"])), v["reason"])
        for v in (result.get("violations") or [])
    ]


def violation_stats(
    results_dir: Path, cells: dict[tuple[str, str, str], dict] | None = None
) -> dict[str, object]:
    """Protocol-failure taxonomy over results/llm/.

    Counted twice, both from populations defined elsewhere so this function
    invents no third one: over the CANONICAL selection (canonical_selection's
    selected episodes -- exactly what the main table scores), and over every
    stored run directory, which additionally includes superseded re-runs and
    the completed no-summary partials.
    """
    if cells is None:
        cells, _ = canonical_selection(results_dir)

    canonical: dict[tuple[str, str], int] = defaultdict(int)
    stored: dict[tuple[str, str], int] = defaultdict(int)
    calls: dict[str, int] = defaultdict(int)
    stored_calls: dict[str, int] = defaultdict(int)
    canonical_episodes = 0
    stored_episodes = 0
    stored_no_summary_episodes = 0
    retries = 0
    guess_phase = 0
    by_model: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))

    for record in scan_run_dirs(results_dir):
        # An unidentifiable dir gets its own bucket rather than being silently
        # attributed to the OpenAI fallback route.
        route = route_of(record.model) if record.model else "unidentified"
        for ep_path in record.seed_paths:
            episode = json.loads(ep_path.read_text(encoding="utf-8"))
            result = episode["result"]
            stored_episodes += 1
            if not record.has_summary:
                stored_no_summary_episodes += 1
            stored_calls[route] += result.get("api_calls") or 0
            for cls, _reason in _violations_of(episode, result):
                stored[(route, cls)] += 1

    for cell in cells.values():
        route = route_of(cell["model"])
        for ep in cell["episodes"]:
            episode = json.loads(ep.path.read_text(encoding="utf-8"))
            result = episode["result"]
            canonical_episodes += 1
            calls[route] += ep.api_calls
            retries += result.get("total_retries") or 0
            for cls, reason in _violations_of(episode, result):
                canonical[(route, cls)] += 1
                by_model[cell["model"]][cls] += 1
                by_model[cell["model"]]["total"] += 1
                if reason.startswith("guess failed"):
                    guess_phase += 1

    worst_model = max(by_model, key=lambda m: by_model[m]["total"]) if by_model else ""
    return {
        "canonical": dict(canonical),
        "stored": dict(stored),
        "calls": dict(calls),
        "stored_calls": dict(stored_calls),
        "canonical_episodes": canonical_episodes,
        "stored_episodes": stored_episodes,
        "stored_no_summary_episodes": stored_no_summary_episodes,
        "canonical_cells": len(cells),
        "retries": retries,
        "guess_phase": guess_phase,
        "total": sum(canonical.values()),
        "stored_total": sum(stored.values()),
        "stored_openrouter": sum(v for (r, _), v in stored.items() if r == "OpenRouter"),
        "worst_model": worst_model,
        "worst_model_total": by_model[worst_model]["total"] if worst_model else 0,
        "worst_model_empty": by_model[worst_model]["empty"] if worst_model else 0,
    }


def violations_table(stats: dict[str, object]) -> str:
    canonical = stats["canonical"]
    calls = stats["calls"]
    lines = [
        GENERATED_HEADER,
        "\\begin{tabular}{@{}l r r r r r@{}}",
        "\\toprule",
        "Recorded failure & " + " & ".join(ROUTES) + " & All \\\\",
        "\\midrule",
    ]
    for cls, label in VIOLATION_CLASSES:
        counts = [canonical.get((route, cls), 0) for route in ROUTES]
        lines.append(f"{label} & " + " & ".join(str(c) for c in counts) + f" & {sum(counts)} \\\\")
    lines.append("\\midrule")
    totals = [sum(canonical.get((route, cls), 0) for cls, _ in VIOLATION_CLASSES) for route in ROUTES]
    lines.append(
        "Violations (forfeits and zeroed guesses) & "
        + " & ".join(str(t) for t in totals)
        + f" & {sum(totals)} \\\\"
    )
    call_counts = [calls.get(route, 0) for route in ROUTES]
    lines.append(
        "Scored game calls & "
        + " & ".join(f"{c:,}".replace(",", "{,}") for c in call_counts)
        + " & "
        + f"{sum(call_counts):,}".replace(",", "{,}")
        + " \\\\"
    )
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    return "\n".join(lines)


