def harness_pairs(
    retained: dict[tuple[str, str, str], dict],
    visible: dict[tuple[str, str, str], dict],
) -> list[dict]:
    """Every cell collected under both harnesses, paired seed by seed."""
    rows = []
    for key, cell in retained.items():
        old = visible.get(key)
        if not old:
            continue
        r_by = {ep.seed: ep for ep in cell["episodes"]}
        v_by = {ep.seed: ep for ep in old["episodes"]}
        seeds = sorted(set(r_by) & set(v_by))
        if not seeds:
            continue
        n = len(seeds)
        diffs = [r_by[s].board_accuracy - v_by[s].board_accuracy for s in seeds]
        mean = sum(diffs) / n
        sem = ((sum((d - mean) ** 2 for d in diffs) / max(n - 1, 1) / n) ** 0.5) if n > 1 else 0.0
        docs_r = {s: _episode_doc(r_by[s].path) for s in seeds}
        docs_v = {s: _episode_doc(v_by[s].path) for s in seeds}
        calls_r = [final_flip(docs_r[s]) for s in seeds]
        calls_v = [final_flip(docs_v[s]) for s in seeds]
        rows.append({
            "model": cell["model"], "tier": cell["tier"], "effort": cell["effort"], "n": n,
            "seeds": seeds,
            "visible": sum(v_by[s].board_accuracy for s in seeds) / n,
            "retained": sum(r_by[s].board_accuracy for s in seeds) / n,
            "delta": mean, "sem": sem,
            "up": sum(1 for d in diffs if d > 1e-9),
            "down": sum(1 for d in diffs if d < -1e-9),
            "visible_ktok": sum(v_by[s].output_tokens for s in seeds) / n / 1000,
            "retained_ktok": sum(r_by[s].output_tokens for s in seeds) / n / 1000,
            # The same paired difference with each final coin flip scored at
            # its expectation (flip_neutral_accuracy), and each arm's flips.
            "delta_flip": sum(
                flip_neutral_accuracy(docs_r[s]) - flip_neutral_accuracy(docs_v[s]) for s in seeds
            ) / n,
            "flips_retained": (sum(1 for c in calls_r if c), sum(1 for c in calls_r if c is not None)),
            "flips_visible": (sum(1 for c in calls_v if c), sum(1 for c in calls_v if c is not None)),
        })
    rows.sort(key=lambda r: (MODEL_ORDER.get(r["model"], 99), EFFORT_ORDER.get(r["effort"], 99),
                             TIER_ORDER.get(r["tier"], 999)))
    return rows


