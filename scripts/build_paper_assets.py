    parser.add_argument("--results", default=PRIMARY_TREE)
    parser.add_argument("--legacy", default=LEGACY_TREE,
                        help="visible-transcript comparison tree")
    parser.add_argument("--out", default="paper/tables")
    parser.add_argument(
        "--freeze",
        action="store_true",
        help="write paper/snapshot_manifest.json pinning the current results tree, then exit",
    )
    parser.add_argument(
        "--skip-gates",
        action="store_true",
        help="rebuild the numbers only: skip the readiness gates (test suite, transcript audit) "
             "and leave readiness_gates.tex as it is",
    )
    args = parser.parse_args(argv)

    results_dir = (REPO_ROOT / args.results).resolve()

    extra_trees = [REPO_ROOT / tree for tree in SNAPSHOT_EXTRA_TREES]

    if args.freeze:
        manifest = build_snapshot_manifest(results_dir, extra_trees)
        SNAPSHOT_MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
        SNAPSHOT_MANIFEST_PATH.write_text(
            json.dumps(manifest, indent=1, sort_keys=True) + "\n", encoding="utf-8"
        )
        try:
            shown = SNAPSHOT_MANIFEST_PATH.relative_to(REPO_ROOT)
        except ValueError:
            shown = SNAPSHOT_MANIFEST_PATH
        print(
            f"Wrote {shown} ({len(manifest['runs'])} run dirs pinned across "
            f"{len(manifest['trees'])} tree(s): {manifest['included']} included, "
            f"{manifest['excluded_no_summary']} excluded-no-summary; "
            f"generator commit {manifest['generator_git']['commit']})"
        )
        return 0

    enforce_freeze_if_frozen(results_dir)

    output_dir = (REPO_ROOT / args.out).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    # ONE selection, reused by every asset below (and imported by make_figures).
    cells, anomalies = canonical_selection(results_dir)
    legacy_cells, legacy_anomalies = canonical_selection((REPO_ROOT / args.legacy).resolve())
    pairs = harness_pairs(cells, legacy_cells)

    main_results_path = output_dir / "cell_grid.tex"
    main_results_path.write_text(cell_grid_table(cells), encoding="utf-8")

    legacy_results_path = output_dir / "cell_grid_legacy.tex"
    legacy_results_path.write_text(cell_grid_table(legacy_cells), encoding="utf-8")

    boards_path = output_dir / "boards.tex"
    boards_path.write_text(boards_table(cells), encoding="utf-8")

    harness_path = output_dir / "harness_comparison.tex"
    confound = prompt_version_confound(pairs, legacy_cells)
    prompt_changed = frozenset((r["model"], r["tier"], r["effort"]) for r in confound["changed"])
    harness_path.write_text(harness_comparison_table(pairs, prompt_changed), encoding="utf-8")

    effort_sweep_path = output_dir / "effort_sweep.tex"
    effort_sweep_path.write_text(effort_sweep_table(cells), encoding="utf-8")

    tiers_path = output_dir / "tiers.tex"
    tiers_path.write_text(tiers_table(cells), encoding="utf-8")

    usage_path = output_dir / "usage.tex"
    usage_path.write_text(usage_table(cells), encoding="utf-8")

    cells_csv_path = output_dir / "cells.csv"
    cells_csv_path.write_text(cells_csv(cells), encoding="utf-8")
    cells_visible_csv_path = output_dir / "cells_visible.csv"
    cells_visible_csv_path.write_text(cells_csv(legacy_cells), encoding="utf-8")

    violations = violation_stats(results_dir, cells)
    violations_path = output_dir / "violations.tex"
    violations_path.write_text(violations_table(violations), encoding="utf-8")

    readiness_gates_path = output_dir / "readiness_gates.tex"
    gates = [] if args.skip_gates else readiness_gates()
    if not args.skip_gates:
        readiness_gates_path.write_text(readiness_gates_table(gates), encoding="utf-8")

    retention_path = output_dir / "retention.tex"
    retention_path.write_text(retention_table(cells), encoding="utf-8")

    cell_macros_path = output_dir / "cell_macros.tex"
    cell_macros_path.write_text(cell_macros_tex(cells, legacy_cells, pairs), encoding="utf-8")

    snapshot_macros_path = output_dir / "snapshot_macros.tex"
