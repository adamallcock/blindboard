def load_calibration_best(calibration_dir: Path) -> dict[str, float]:
    """Certificate value per tier across results/calibration/
    calibration-*.json files. Solver-v3 policy: a tier calibrated with the
    shipped 'planner' agent (hash-seed-pinned runs, 2026-07-18+) uses the
    planner value from the LATEST calibration file (sorted by filename)
    containing a planner entry for that tier, and IGNORES reference values
    for that tier -- pre-pin reference numbers are per-PYTHONHASHSEED
    realizations and may be unreproducibly high. Tiers never run under the
    planner fall back to the latest file with a reference entry.

    Latest, NOT max: taking the max across files is upward-biased on
    re-calibration (each file is one finite-seed realization)."""
    latest_planner: dict[str, float] = {}
    latest_reference: dict[str, float] = {}
    for path in sorted(calibration_dir.glob("calibration-*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        for tier, agents in (data.get("table") or {}).items():
            for agent, latest in (("planner", latest_planner), ("reference", latest_reference)):
                value = ((agents or {}).get(agent) or {}).get("board_accuracy_mean")
                if value is not None:
                    latest[tier] = value  # sorted iteration: later files overwrite
    return {**latest_reference, **latest_planner}


def tier_certificates_gate(calibration_dir: Path | None = None) -> tuple[str, str]:
    best = load_calibration_best(calibration_dir or REPO_ROOT / "results" / "calibration")
    all_tiers = sorted(TIERS, key=lambda t: TIER_ORDER[t])

    raw = {t: best[t] for t in all_tiers if t in best}
    # Anchor every certificate at its analytic ceiling: a finite-seed
    # calibration can land above the expected ceiling by seed luck, and the
    # anchored value min(certificate, ceiling) is what gates/normalization
    # use. Both numbers are carried; above-ceiling tiers are counted below.
    calibrated = {t: min(v, CEILINGS.get(t, 1.0)) for t, v in raw.items()}
    above_ceiling = [t for t, v in raw.items() if v > CEILINGS.get(t, 1.0)]
    uncalibrated = [t for t in all_tiers if t not in calibrated]
    passing = {t: v for t, v in calibrated.items() if v >= CERTIFICATION_THRESHOLD}
    failing = {t: v for t, v in calibrated.items() if v < CERTIFICATION_THRESHOLD}

    if not uncalibrated and not failing:
        status = "PASS"
    elif not failing:
        status = "WARN"
    else:
        # A tier with real calibration data below threshold is a genuine
        # certification failure, not a "not yet measured" gap -- the WARN
        # exception in the spec covers only missing-entry tiers, so this
        # does not get downgraded from FAIL.
        status = "FAIL"

    parts: list[str] = []
    if passing:
        worst_tier = min(passing, key=lambda t: passing[t])
        parts.append(f"{len(passing)} tiers certified, min ref {fmt_dec(passing[worst_tier])} at {worst_tier}")
    else:
        parts.append("0 tiers certified")
    if above_ceiling:
        count = len(above_ceiling)
        parts.append(
            f"{count} certificate{'s' if count != 1 else ''} above "
            f"{'their' if count != 1 else 'its'} analytic "
            f"ceiling{'s' if count != 1 else ''} (seed luck, anchored at ceiling)"
        )
    if failing:
        detail = "; ".join(f"{t} {fmt_dec(v)}" for t, v in failing.items())
        parts.append(f"below {fmt_dec(CERTIFICATION_THRESHOLD, 2)} threshold: {detail}")
    if uncalibrated:
        parts.append(f"uncalibrated: {', '.join(uncalibrated)}")

    # Known, documented nuances worth surfacing rather than leaving as a bare
    # number -- both were found by cross-referencing blindboard/tiers.py.
    notes: list[str] = []
    if "t8_storm" in failing:
        notes.append(
            "t8_storm's calibrated reference matches tiers.py's comment for "
            "the rejected constant-churn design (.208), not the documented "
            ".892 ceiling for the schedule actually in TIERS -- calibration "
            "is likely stale"
        )
    if "t10_relabel" in uncalibrated:
        notes.append(
            "t10_relabel has no calibration file entry, but tiers.py "
            "documents its ceiling as analytically inherited from "
            "t7_perpetual since relabeling does not affect the scripted "
            "reference"
        )
    if notes:
        parts.append("; ".join(notes))

    return status, "; ".join(parts) + "."


def cells_csv(cells: dict[tuple[str, str, str], dict]) -> str:
    """Every cell as one CSV row, for readers who want the numbers outside
    LaTeX: mean board accuracy and its SEM, boards solved, output tokens per
    episode, and the list cost of the episodes the cell reports."""
    rows = ["model,tier,effort,n,accuracy,sem,boards_solved,output_tokens_per_episode,list_cost_usd"]
    for (model, tier, effort), cell in sorted(cells.items(), key=lambda kv: (
            MODEL_ORDER.get(kv[0][0], 99), kv[0][0], list(TIERS).index(kv[0][1]) if kv[0][1] in TIERS else 99,
            EFFORT_ORDER.get(kv[0][2], 99))):
        if not cell["n"]:
            continue
        rows.append(",".join([
            model, tier, effort, str(cell["n"]), f"{cell['mean']:.4f}", f"{cell['sem']:.4f}",
            str(cell.get("solves", 0)), f"{cell['output_tokens'] / cell['n']:.0f}", f"{cell['cost_usd']:.4f}",
        ]))
    return "\n".join(rows) + "\n"


