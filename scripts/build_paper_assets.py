    z = audit["max_abs_z"]
    p_one = math.erfc(z / math.sqrt(2))
    macro("derangementrotations", _grouped(audit["rotations"]))
    macro("derangementtests", len(audit["tests"]))
    macro("derangementmaxz", f"{z:.2f}")
    # Bonferroni: valid however the overlapping tests depend on each other.
    macro("derangementfamilyp", fmt_dec(min(1.0, len(audit["tests"]) * p_one), 2))
    macro("derangementtallyhit", f"{100 * audit['tally_hit_rate']:.1f}")

    confound = prompt_version_confound(pairs, legacy_cells)
    macro("legacyoldpromptcells", confound["cells"])
    macro("legacyoldpromptchangedcells", confound["changed_cells"])
    macro("legacyoldpromptchangedpairs", confound["changed_pairs"])

    cost = harness_cost_stats(pairs, cells, legacy_cells)
    macro("harnesscostretained", _usd(cost["retained"]))
    macro("harnesscostvisible", _usd(cost["visible"]))
    macro("harnesscostratio", f"{cost['retained'] / cost['visible']:.2f}" if cost["visible"] else "--")
    macro("harnessinputratio", f"{cost['input_ratio_median']:.1f}")

    held = heldout_calibration(repo_root)
    if held:
        macro("heldoutseedstart", _grouped(held["seed_start"]))
        macro("heldoutseedend", _grouped(held["seed_start"] + held["seeds"] - 1))
        macro("heldoutseeds", held["seeds"])
        macro("heldouttiers", len(held["rows"]))
        macro("heldoutmaxgap", f"{100 * abs(held['worst']['gap']):.1f}")
        macro("heldoutmaxgaptier", latex_escape(held["worst"]["tier"]))
        macro("heldoutmaxz", f"{held['max_abs_z']:.1f}")
        macro("heldoutabove", len(held["above"]))
        macro("heldoutaboveback", held["above_back"])
    return lines


