@dataclass(frozen=True)
class RunDirRecord:
    """One stored run directory, whether or not it ever wrote a summary."""

    path: Path
    tree: str  # repo-relative tree root, e.g. "results/llm"
    name: str  # path relative to that tree root
    summary: dict | None
    model: str | None  # registry model id
    tier: str | None
    effort: str | None  # requested effort label, before any same-config merge
    seed_paths: tuple[Path, ...]
    # run_llm's record of a run whose every episode failed (billed, unscored).
    failed_run: dict | None = None

    @property
    def has_summary(self) -> bool:
        return self.summary is not None

    @property
    def status(self) -> str:
        return "included" if self.has_summary else "excluded-no-summary"


@dataclass(frozen=True)
class EpisodeRecord:
    """One scored episode, already attributed to a canonical cell."""

    seed: int
    path: Path
    run_dir: str
    model: str
    tier: str
    effort: str  # CANONICAL effort label (post same-config merge)
    board_accuracy: float
    api_calls: int
    input_tokens: int
    output_tokens: int
    cost_usd: float
    lock_wrong: int


def pricing_key(model: str | None) -> str | None:
    """Key into the vendored list-price registry for a registry model id, or
    None when the registry has no entry. Summaries record OpenAI models bare
    ('gpt-5.6-luna') and Anthropic ones without their provider ('claude-opus-4-8'),
    while the registry namespaces the latter."""
    if model is None:
        return None
    if model in PRICES:
        return model
    slug = provider_slug(model)
    return slug if slug in PRICES else None


# The first retained OpenAI runs recorded cached input under the Responses
# API's own name; the registry prices it as cache_read_tokens.
USAGE_ALIASES = {"cached_input_tokens": "cache_read_tokens"}


def normalize_usage(usage: dict) -> dict:
    """A usage-totals dict with legacy field names mapped to the registry's.
    Refuses one that carries both names with different counts."""
    out = dict(usage)
    for legacy, name in USAGE_ALIASES.items():
        if legacy not in out:
            continue
        value = out.pop(legacy)
        if name in out and out[name] != value:
            raise ValueError(f"usage records {legacy}={value} and {name}={out[name]}")
        out[name] = value
    return out


def usage_cost(model: str | None, usage: dict | None, on: str | None = None) -> float | None:
    """List-price cost for a usage-totals dict on ISO date ``on`` (None: the
    earliest verified price), or None if unpriceable."""
    key = pricing_key(model)
    if key is None or not usage:
        return None
    return list_price_usd(key, normalize_usage(usage), on=on)


def run_date(name: str) -> str | None:
    """ISO collection date from a run-directory name's -YYYYMMDD-HHMMSS stamp."""
    match = _RUN_DIR_NAME_RE.match(Path(name).name)
    if match is None:
        return None
    stamp = match.group("stamp")
    return f"{stamp[0:4]}-{stamp[4:6]}-{stamp[6:8]}"


def harness_cost(doc: dict) -> float | None:
    """Sum of the per-request list costs a retained-harness transcript records
    (each request priced at the published standard-tier rate of its day), or
    None when the transcript carries no complete set of them."""
    calls = [m for m in doc.get("transcript") or () if isinstance(m, dict) and m.get("role") == "assistant"]
    if not calls or not all("cost_usd_list" in m for m in calls):
        return None
    costs = [m.get("cost_usd_list") for m in calls]
    return None if any(c is None for c in costs) else float(sum(costs))


def episode_list_cost(model: str | None, doc: dict, on: str | None) -> float | None:
    """One stored episode's list cost: the harness's own per-request prices
    when recorded, else the registry price of its usage on its collection day."""
    recorded = harness_cost(doc)
    if recorded is not None:
        return recorded
    return usage_cost(model, (doc.get("result") or {}).get("usage") or {}, on=on)


def identity_from_dir_name(name: str) -> tuple[str | None, str | None, str | None]:
    """(model, tier, effort) parsed out of a run-directory name.

    The naming contract is scripts/run_llm.py's
    "{model with / -> -}-{effort}-{tier}-{stamp}". This is what makes a
    summary-less run dir accountable instead of anonymous.
    """
    match = _RUN_DIR_NAME_RE.match(name)
    if match is None:
        return (None, None, None)
    rest = match.group("rest")
    for model in KNOWN_RUN_DIR_MODELS:
        prefix = model.replace("/", "-") + "-"
        if rest.startswith(prefix):
            effort, _, tier = rest[len(prefix) :].partition("-")
            tier = tier.removeprefix("retained-")  # run_llm --harness retained tag
            return (model, tier or None, effort or None)
    return (None, None, None)


def iter_run_dirs(tree: Path) -> list[Path]:
    """Every directory under `tree` holding run artifacts (a summary.json or
    any seed*.json), sorted. Recursive: results/llm is flat, but the
    robustness arm nests its runs one level down under a campaign folder."""
    if not tree.exists():
        return []
    return sorted(
        p
        for p in tree.rglob("*")
        if p.is_dir()
        and (
            (p / "summary.json").exists()
            or (p / "failed_run.json").exists()
            or any(p.glob("seed*.json"))
        )
    )


def _tree_label(tree: Path) -> str:
    try:
        return tree.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return tree.name


def scan_run_dirs(tree: Path) -> list[RunDirRecord]:
    """Classify EVERY run directory under `tree`, summary or not."""
    label = _tree_label(tree)
    records: list[RunDirRecord] = []
    for run_dir in iter_run_dirs(tree):
        summary_path = run_dir / "summary.json"
        summary = (
            json.loads(summary_path.read_text(encoding="utf-8"))
            if summary_path.exists()
            else None
        )
        failed_path = run_dir / "failed_run.json"
        failed_run = (
            json.loads(failed_path.read_text(encoding="utf-8")) if failed_path.exists() else None
        )
        if summary is not None:
            model, tier, effort = summary.get("model"), summary.get("tier"), summary.get("effort")
        elif failed_run is not None:
            model, tier, effort = (
                failed_run.get("model"), failed_run.get("tier"), failed_run.get("effort")
            )
        else:
            model, tier, effort = identity_from_dir_name(run_dir.name)
        records.append(
            RunDirRecord(
                path=run_dir,
                tree=label,
                name=run_dir.relative_to(tree).as_posix(),
                summary=summary,
                model=model,
                tier=tier,
                effort=effort,
                seed_paths=tuple(sorted(run_dir.glob("seed*.json"))),
                failed_run=failed_run,
            )
        )
    return records


